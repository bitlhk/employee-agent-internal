CREATE TABLE `custom_mcp_call_receipts` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `request_id` varchar(64) NOT NULL,
  `policy_decision_id` varchar(64) NOT NULL,
  `idempotency_key` varchar(191) NOT NULL,
  `status` enum('started','completed','failed','blocked') NOT NULL DEFAULT 'started',
  `connection_id` bigint NOT NULL,
  `tool_name` varchar(256) NOT NULL,
  `user_id` int NOT NULL,
  `adopt_id` varchar(64) NOT NULL,
  `args_hash` varchar(64) NOT NULL,
  `result_hash` varchar(64) NULL,
  `external_request_id` varchar(128) NULL,
  `duration_ms` int NULL,
  `error_code` varchar(128) NULL,
  `started_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `completed_at` timestamp NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_custom_mcp_call_request` (`request_id`),
  UNIQUE KEY `uk_custom_mcp_call_idempotency` (`adopt_id`, `connection_id`, `tool_name`, `idempotency_key`),
  KEY `idx_custom_mcp_call_actor_started` (`user_id`, `started_at`),
  KEY `idx_custom_mcp_call_connection_started` (`connection_id`, `started_at`),
  KEY `idx_custom_mcp_call_status_started` (`status`, `started_at`)
);
